export function mergeIndustryPageAr(slug: string, industryTitleAr: string): ModuleRichPage {
  const base = buildArabicIndustryGeneric(industryTitleAr)
  const o = industryOverridesAr[slug]
  if (!o) return base
  return {
    ...base,
    ...o,
    highlights: o.highlights ?? base.highlights,
    capabilities: o.capabilities ?? base.capabilities,
    workflows: o.workflows ?? base.workflows,
    outcomes: o.outcomes ?? base.outcomes,
  }
}
